// SetClientInbounds replaces a client's grants with the given desired set. Grant
// rows are enabled by default. Unknown inbound ids are ignored by the FK.
func (s *Store) SetClientInbounds(ctx context.Context, clientID int64, inboundIDs []int64) error {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer func() { _ = tx.Rollback() }()

	if _, err := tx.ExecContext(ctx, "DELETE FROM client_inbounds WHERE client_id = ?", clientID); err != nil {
		return err
	}
	now := nowRFC3339()
	for _, inb := range inboundIDs {
		if _, err := tx.ExecContext(ctx, `
			INSERT INTO client_inbounds (client_id, inbound_id, enabled, created_at)
			VALUES (?, ?, 1, ?)`, clientID, inb, now); err != nil {
			return err
		}
	}
	return tx.Commit()
}

const clientGrantSelect = `
	SELECT ci.inbound_id, s.id, s.name, s.host, i.tag, i.protocol, i.enabled, ci.enabled
	FROM client_inbounds ci
	JOIN inbounds i ON i.id = ci.inbound_id
	JOIN servers  s ON s.id = i.server_id
	WHERE ci.client_id = ?
	ORDER BY s.id ASC, i.id ASC`

// ListClientGrants returns a client's grants with server/inbound context.
func (s *Store) ListClientGrants(ctx context.Context, clientID int64) ([]ClientGrant, error) {
	rows, err := s.db.QueryContext(ctx, clientGrantSelect, clientID)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	out := []ClientGrant{}
	for rows.Next() {
		var g ClientGrant
		var inboundOn, grantOn int64
		if err := rows.Scan(&g.InboundID, &g.ServerID, &g.ServerName, &g.ServerHost,
			&g.InboundTag, &g.Protocol, &inboundOn, &grantOn); err != nil {
			return nil, err
		}
		g.InboundOn = inboundOn != 0
		g.GrantEnabled = grantOn != 0
		out = append(out, g)
	}
	return out, rows.Err()
}

// inboundWithServerSelect projects a full inbound plus its server host/name.
const inboundWithServerSelect = `
	SELECT i.id, i.server_id, i.tag, i.protocol, i.listen, i.port,
	       i.settings_json, i.stream_settings_json, i.sniffing_json, i.remark, i.enabled,
	       i.created_at, i.updated_at,
	       (SELECT COUNT(*) FROM client_inbounds WHERE inbound_id = i.id) AS client_count,
	       s.host, s.name
	FROM inbounds i
	JOIN servers s ON s.id = i.server_id`

// ListActiveClientInbounds returns the full inbounds a client should appear in:
// grant enabled AND inbound enabled. Used to build subscription URIs. The client
// being disabled is the caller's responsibility to check.
func (s *Store) ListActiveClientInbounds(ctx context.Context, clientID int64) ([]InboundWithServer, error) {
	rows, err := s.db.QueryContext(ctx, inboundWithServerSelect+`
		JOIN client_inbounds ci ON ci.inbound_id = i.id
		WHERE ci.client_id = ? AND ci.enabled = 1 AND i.enabled = 1
		ORDER BY s.id ASC, i.id ASC`, clientID)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	return scanInboundsWithServer(rows)
}

// ListInboundGrantedClients returns the enabled clients that hold an enabled
// grant to an inbound. Used by sync to assemble each engine's config.
func (s *Store) ListInboundGrantedClients(ctx context.Context, inboundID int64) ([]Client, error) {
	rows, err := s.db.QueryContext(ctx, `
		SELECT c.id, c.name, c.uuid, c.password, c.subscription_token, c.enabled, c.remark,
		       c.created_at, c.updated_at, c.email, c.tg_chat_id, c.tg_username, c.tg_link_token,
		       c.wallet_kopecks, c.active_until, c.billing_managed, c.billing_exempt
		FROM client_inbounds ci
		JOIN clients c ON c.id = ci.client_id
		WHERE ci.inbound_id = ? AND ci.enabled = 1 AND c.enabled = 1
		ORDER BY c.id ASC`, inboundID)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []Client
	for rows.Next() {
		c, err := scanClient(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, *c)
	}
	return out, rows.Err()
}

// scanInboundsWithServer scans rows selected via inboundSelect joined with the
// server host/name appended as the last two columns.
func scanInboundsWithServer(rows *sql.Rows) ([]InboundWithServer, error) {
	out := []InboundWithServer{}
	for rows.Next() {
		var in Inbound
		var enabled int64
		var host, name string
		if err := rows.Scan(&in.ID, &in.ServerID, &in.Tag, &in.Protocol, &in.Listen, &in.Port,
			&in.SettingsJSON, &in.StreamSettingsJSON, &in.SniffingJSON, &in.Remark, &enabled,
			&in.CreatedAt, &in.UpdatedAt, &in.ClientCount, &host, &name); err != nil {
			return nil, err
		}
		in.Enabled = enabled != 0
		out = append(out, InboundWithServer{Inbound: in, ServerHost: host, ServerName: name})
	}
	return out, rows.Err()
}

// GetClientParams returns the client's per-client protocol params JSON blob
// (defaults to "{}" for a client that has none yet).
func (s *Store) GetClientParams(ctx context.Context, id int64) (string, error) {
	var v string
	err := s.db.QueryRowContext(ctx, "SELECT params_json FROM clients WHERE id = ?", id).Scan(&v)
	if errors.Is(err, sql.ErrNoRows) {
		return "", ErrNotFound
	}
	if err != nil {
		return "", err
	}
	if v == "" {
		v = "{}"
	}
	return v, nil
}

// SetClientParams writes the client's per-client protocol params JSON blob.
func (s *Store) SetClientParams(ctx context.Context, id int64, paramsJSON string) error {
	res, err := s.db.ExecContext(ctx, "UPDATE clients SET params_json = ? WHERE id = ?", paramsJSON, id)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}
