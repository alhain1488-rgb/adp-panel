// Client is a subscriber that may be granted access to inbounds.
type Client struct {
	ID                int64
	Name              string
	UUID              string
	Password          string
	SubscriptionToken string
	Enabled           bool
	Remark            string
	Email             string
	TelegramChatID    string // numeric chat id once the client links their Telegram
	TelegramUsername  string // @handle, display only
	TelegramLinkToken string // deep-link payload that binds a chat to this client
	WalletKopecks     int64  // prepaid balance in kopecks (100 = 1 RUB)
	ActiveUntil       string // subscription expiry (RFC3339); "" = no billed subscription
	BillingManaged    bool   // true once the client has bought a subscription
	BillingExempt     bool   // lifetime free access: never auto-suspended
	CreatedAt         string
	UpdatedAt         string
}

// ClientParams holds the writable/generated fields for create.
type ClientParams struct {
	Name              string
	UUID              string
	Password          string
	SubscriptionToken string
	Enabled           bool
	Remark            string
	Email             string
	TelegramLinkToken string
}

// ClientGrant is an inbound granted to a client, with server context, as shown
// in the UI. It does not carry the full inbound settings.
type ClientGrant struct {
	InboundID    int64
	ServerID     int64
	ServerName   string
	ServerHost   string
	InboundTag   string
	Protocol     string
	InboundOn    bool // inbounds.enabled
	GrantEnabled bool // client_inbounds.enabled
}

// InboundWithServer carries a full inbound plus its server host/name, used to
// build subscription URIs and engine configs.
type InboundWithServer struct {
	Inbound
	ServerName string
	ServerHost string
}

const clientSelect = `
	SELECT id, name, uuid, password, subscription_token, enabled, remark, created_at, updated_at, email,
	       tg_chat_id, tg_username, tg_link_token, wallet_kopecks, active_until, billing_managed, billing_exempt
	FROM clients`

func scanClient(sc interface{ Scan(...any) error }) (*Client, error) {
	var c Client
	var enabled, managed, exempt int64
	err := sc.Scan(&c.ID, &c.Name, &c.UUID, &c.Password, &c.SubscriptionToken,
		&enabled, &c.Remark, &c.CreatedAt, &c.UpdatedAt, &c.Email,
		&c.TelegramChatID, &c.TelegramUsername, &c.TelegramLinkToken,
		&c.WalletKopecks, &c.ActiveUntil, &managed, &exempt)
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return nil, ErrNotFound
		}
		return nil, err
	}
	c.Enabled = enabled != 0
	c.BillingManaged = managed != 0
	c.BillingExempt = exempt != 0
	return &c, nil
}

// SetClientBillingExempt grants or revokes lifetime free access.
func (s *Store) SetClientBillingExempt(ctx context.Context, id int64, exempt bool) (*Client, error) {
	res, err := s.db.ExecContext(ctx,
		"UPDATE clients SET billing_exempt = ?, updated_at = ? WHERE id = ?",
		boolToInt(exempt), nowRFC3339(), id)
	if err != nil {
		return nil, err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return nil, ErrNotFound
	}
	return s.GetClient(ctx, id)
}

// ListClients returns all clients, oldest first.
func (s *Store) ListClients(ctx context.Context) ([]Client, error) {
	rows, err := s.db.QueryContext(ctx, clientSelect+" ORDER BY id ASC")
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []Client
	for rows.Next() {
		c, err := scanClient(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, *c)
	}
	return out, rows.Err()
}

// GetClient returns a client by id.
func (s *Store) GetClient(ctx context.Context, id int64) (*Client, error) {
	return scanClient(s.db.QueryRowContext(ctx, clientSelect+" WHERE id = ?", id))
}

// GetClientByToken returns a client by its subscription token.
func (s *Store) GetClientByToken(ctx context.Context, token string) (*Client, error) {
	return scanClient(s.db.QueryRowContext(ctx, clientSelect+" WHERE subscription_token = ?", token))
}

// CreateClient inserts a client (uuid/password/token are generated by the caller).
func (s *Store) CreateClient(ctx context.Context, p ClientParams) (*Client, error) {
	now := nowRFC3339()
	res, err := s.db.ExecContext(ctx, `
		INSERT INTO clients (name, uuid, password, subscription_token, enabled, remark, email, tg_link_token, created_at, updated_at)
		VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		p.Name, p.UUID, p.Password, p.SubscriptionToken, boolToInt(p.Enabled), p.Remark, p.Email, p.TelegramLinkToken, now, now)
	if err != nil {
		return nil, err
	}
	id, err := res.LastInsertId()
	if err != nil {
		return nil, err
	}
	return s.GetClient(ctx, id)
}

// UpdateClient changes the name, remark and contact e-mail.
func (s *Store) UpdateClient(ctx context.Context, id int64, name, remark, email string) (*Client, error) {
	if _, err := s.db.ExecContext(ctx,
		"UPDATE clients SET name=?, remark=?, email=?, updated_at=? WHERE id=?",
		name, remark, email, nowRFC3339(), id); err != nil {
		return nil, err
	}
	return s.GetClient(ctx, id)
}

